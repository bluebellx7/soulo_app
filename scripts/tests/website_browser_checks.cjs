/* Run against a local website server. See website/README.md. */
const assert = require('node:assert/strict');
const {chromium} = require(process.env.SOULO_PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.SOULO_WEBSITE_URL || 'http://127.0.0.1:8765';
const errors = [];
const movieData = require('../../website/movies.json');
const magnetData = require('../../website/magnets.json');
const panData = require('../../website/pans.json');
const stockData = require('../../website/stocks.json');
const readingData = require('../../website/reading.json');
const musicData = require('../../website/music.json');

async function main() {
  const options = {headless: true};
  if (process.env.SOULO_CHROME_PATH) options.executablePath = process.env.SOULO_CHROME_PATH;
  const browser = await chromium.launch(options);
  try {
    const context = await browser.newContext({viewport: {width: 1440, height: 1000}, locale: 'zh-CN', colorScheme: 'light', permissions: ['clipboard-read','clipboard-write']});
    // Local QA must not send production analytics pageviews.
    await context.route('https://hm.baidu.com/**', route => route.abort());
    context.on('page', page => page.on('pageerror', error => errors.push(error.message)));
    const page = await context.newPage();
    await page.goto(base+'/movies.html');
    const total = await page.locator('.movie-card').count();
    assert.equal(total, movieData.sites.length);
    const visible = () => page.locator('.movie-card:visible').count();
    await page.locator('#movie-search').fill('PBKAN.COM');
    assert.equal(await visible(), 1);
    assert.match(await page.locator('.movie-card:visible h3').innerText(), /片吧影视/);
    await page.locator('#movie-search').fill('电影 下载');
    assert.ok(await visible() > 0);
    await page.locator('#movie-search').fill('this-site-does-not-exist');
    assert.equal(await visible(), 0);
    assert.ok(await page.locator('#movie-empty').isVisible());
    await page.locator('#reset-filters').click();
    assert.equal(await visible(), total);
    await page.locator('[data-category="anime"]').click();
    assert.equal(await visible(), movieData.sites.filter(site => site.category === 'anime').length);
    assert.equal(await page.locator('[data-section]:visible').count(), 1);
    await page.locator('[data-category="all"]').click();
    assert.equal(await page.locator('#favorite-picks').isVisible(), false);
    await page.locator('[data-favorite="pbkan"]').click();
    await page.locator('[data-favorite="6v"]').click();
    await page.locator('[data-favorite="y80s"]').click();
    assert.equal(await page.locator('#favorite-picks').isVisible(), true);
    assert.equal(await page.locator('#favorite-picks-grid .quick-pick').count(), 3);
    await page.locator('[data-favorite="6v"]').click();
    await page.locator('[data-favorite="y80s"]').click();
    assert.equal(await page.locator('#favorite-picks-grid .quick-pick').count(), 1);
    await page.locator('#show-favorites').click();
    assert.equal(await visible(), 1);
    await page.reload();
    assert.equal(await page.locator('[data-favorite="pbkan"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#favorite-picks').isVisible(), true);
    await page.locator('#show-favorites').click();
    assert.equal(await visible(), 1);
    await page.locator('[data-favorite="pbkan"]').click();
    assert.equal(await page.locator('#favorite-picks').isVisible(), false);
    assert.equal(await visible(), 0);
    assert.match(await page.locator('#empty-title').innerText(), /喜欢的入口/);
    await page.locator('#reset-filters').click();
    await page.keyboard.press('/');
    assert.equal(await page.locator('#movie-search').evaluate(e => e === document.activeElement), true);
    await page.keyboard.type('字幕');
    await page.keyboard.press('Escape');
    assert.equal(await visible(), total);
    assert.equal(await page.locator('html').getAttribute('data-resolved-theme'), 'dark');
    await page.locator('#theme-toggle').click();
    assert.equal(await page.locator('html').getAttribute('data-resolved-theme'), 'light');
    const lightBrandLogo = await page.locator('[data-shared-nav] .brand img').evaluate(img => {
      const style = getComputedStyle(img);
      return {borderWidth: style.borderTopWidth, filter: style.filter};
    });
    assert.equal(lightBrandLogo.borderWidth, '1px');
    assert.notEqual(lightBrandLogo.filter, 'none');
    await page.locator('#theme-toggle').click();
    assert.equal(await page.locator('html').getAttribute('data-resolved-theme'), 'dark');
    await page.reload();
    assert.equal(await page.locator('html').getAttribute('data-resolved-theme'), 'dark');
    const cardBackground = await page.locator('.movie-card').first().evaluate(e => getComputedStyle(e).backgroundColor);
    assert.equal(cardBackground, 'rgb(27, 28, 36)');
    const magnetUrls = new Set(magnetData.sites.map(site => site.url));
    const resourceTotal = new Set([...magnetData.sites, ...panData.sites].map(site => site.url)).size;
    await page.evaluate(() => {
      localStorage.setItem('soulo-magnet-favorites', JSON.stringify(['xcili', 'seedhub']));
      localStorage.setItem('soulo-pan-favorites', JSON.stringify(['pan-qianfan', 'seedhub-pan']));
    });
    await page.goto(base+'/magnets.html');
    await page.waitForURL('**/resources.html#magnet');
    assert.equal(await page.locator('[data-resource-group="magnet"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await visible(), magnetData.sites.length);
    assert.equal(await page.locator('[data-category="official"]').isVisible(), false);
    await page.goto(base+'/pans.html');
    await page.waitForURL('**/resources.html#cloud');
    assert.equal(await page.locator('[data-resource-group="cloud"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await visible(), resourceTotal - magnetUrls.size);
    await page.goto(base+'/pans.html#engine');
    await page.waitForURL('**/resources.html#cloud-engine');
    await page.goto(base+'/resources.html');
    assert.equal(await visible(), resourceTotal);
    await page.locator('#movie-search').fill('xcili.net');
    assert.equal(await visible(), 1);
    assert.equal(await page.locator('.movie-card:visible h3').innerText(), '无极磁链镜像');
    await page.locator('#movie-search').fill('qianfan.app');
    assert.equal(await visible(), 1);
    assert.match(await page.locator('.movie-card:visible h3').innerText(), /千帆搜索/);
    await page.locator('[data-resource-group="magnet"]').click();
    assert.equal(await visible(), 0);
    await page.locator('[data-resource-group="cloud"]').click();
    assert.equal(await visible(), 1);
    await page.locator('[data-category="official"]').click();
    assert.equal(await visible(), panData.sites.filter(site => site.category === 'official').length);
    await page.locator('[data-resource-group="magnet"]').click();
    await page.locator('[data-category="anime"]').click();
    assert.equal(await visible(), magnetData.sites.filter(site => site.category === 'anime').length);
    await page.locator('#show-favorites').click();
    assert.equal(await visible(), 3);
    assert.equal(await page.locator('#favorite-picks-grid .quick-pick').count(), 3);
    await page.locator('#show-favorites').click();
    assert.equal(await visible(), resourceTotal);
    await page.locator('[data-favorite="seedhub"]').click();
    await page.reload();
    assert.equal(await page.locator('[data-favorite="seedhub"]').getAttribute('aria-pressed'), 'false');
    assert.equal(await page.locator('#favorite-count').innerText(), '2');
    await page.locator('#movie-search').fill('SeedHub 夸克');
    assert.equal(await visible(), 1);
    await page.locator('#movie-search').fill('this-resource-does-not-exist');
    assert.equal(await visible(), 0);
    await page.locator('#reset-filters').click();
    assert.equal(await visible(), resourceTotal);
    await page.goto(base+'/stocks.html');
    assert.equal(await visible(), stockData.sites.length);
    assert.equal(await page.locator('.movie-card h3').first().innerText(), '牛盘盘');
    assert.equal(await page.locator('.movie-card-link').first().getAttribute('href'), 'https://niupanpan.com/');
    await page.locator('#movie-search').fill('NIUPANPAN.COM');
    assert.equal(await visible(), 1);
    assert.equal(await page.locator('.movie-card:visible h3').innerText(), '牛盘盘');
    await page.locator('#movie-search').clear();
    assert.equal(await page.locator('.movie-card .site-mark img').count(), stockData.sites.length);
    const stockIcons = await page.locator('.movie-card .site-mark img').evaluateAll(async images => {
      for (const image of images) image.loading = 'eager';
      await Promise.all(images.map(image => image.decode()));
      return images.map(image => ({src: image.getAttribute('src'), width: image.naturalWidth, height: image.naturalHeight}));
    });
    assert.ok(stockIcons.every(image => image.width > 0 && image.height > 0 && image.src.startsWith('images/stock-icons/')));
    await page.locator('[data-category="public-data"]').click();
    assert.equal(await visible(), stockData.sites.filter(site => site.category === 'public-data').length);
    assert.equal(await page.locator('.movie-category:visible h2').innerText(), '公共数据');
    await page.locator('#movie-search').fill('FRED 利率');
    assert.equal(await visible(), 1);
    assert.equal(await page.locator('.movie-card:visible h3').innerText(), 'FRED 经济数据');
    await page.locator('#language-toggle').click();
    assert.equal(await page.locator('main h1').innerText(), 'Stocks');
    assert.equal(await page.locator('#movie-search').getAttribute('placeholder'), 'Search sites, domains, or keywords');
    await page.locator('#language-toggle').click();
    await page.locator('[data-favorite="fred"]').click();
    await page.reload();
    await page.locator('#show-favorites').click();
    assert.equal(await visible(), 1);
    assert.equal(await page.locator('.movie-card:visible h3').innerText(), 'FRED 经济数据');
    for (const [kind, data, domain, category, first] of [
      ['reading', readingData, 'IBOOKS.ORG.CN', 'ebooks', 'ibooks'],
      ['music', musicData, 'GEQUBAO.COM', 'search', 'gequbao'],
    ]) {
      await page.goto(base+'/'+kind+'.html');
      assert.equal(await visible(), data.sites.length);
      assert.match(await page.locator('#results-meta').innerText(), kind === 'reading' ? /阅读网站/ : /音乐网站/);
      await page.evaluate(async () => {
        const images = [...document.querySelectorAll('.site-mark img')];
        images.forEach(image => { image.loading = 'eager'; });
        await Promise.all(images.map(image => image.decode()));
      });
      await page.locator('#movie-search').fill(domain);
      assert.equal(await visible(), 1);
      await page.locator('[data-category="'+category+'"]').click();
      assert.equal(await visible(), data.sites.filter(site => site.category === category).length);
      await page.locator('[data-category="all"]').click();
      await page.locator('[data-favorite="'+first+'"]').click();
      await page.reload();
      assert.equal(await page.locator('[data-favorite="'+first+'"]').getAttribute('aria-pressed'), 'true');
      await page.locator('#show-favorites').click();
      assert.equal(await visible(), 1);
      await page.locator('#language-toggle').click();
      assert.equal(await page.locator('.movie-card:visible h3').innerText(), data.sites.find(site => site.id === first).name_en);
      assert.equal(await page.locator('.nav-links a > svg:first-child').count(), 7);
      await page.locator('[data-favorite="'+first+'"]').click();
      assert.equal(await visible(), 0);
      assert.match(await page.locator('#empty-description').innerText(), kind === 'reading' ? /reading list/ : /listening list/);
      await page.locator('#reset-filters').click();
      assert.equal(await visible(), data.sites.length);
      assert.match(await page.locator('#results-meta').innerText(), kind === 'reading' ? /reading websites/ : /music & audio websites/);
      await page.locator('#movie-search').fill('no-such-website');
      assert.equal(await visible(), 0);
      assert.ok(await page.locator('#movie-empty').isVisible());
      await page.locator('#reset-filters').click();
      await page.locator('#language-toggle').click();
    }
    await page.goto(base+'/reading.html');
    await page.locator('[data-favorite="ibooks"]').click();
    await page.goto(base+'/music.html');
    assert.equal(await page.locator('#favorite-count').innerText(), '0');
    await page.locator('[data-favorite="gequbao"]').click();
    await page.goto(base+'/reading.html');
    assert.equal(await page.locator('[data-favorite="ibooks"]').getAttribute('aria-pressed'), 'true');
    await page.locator('[data-favorite="ibooks"]').click();
    await page.goto(base+'/music.html');
    assert.equal(await page.locator('[data-favorite="gequbao"]').getAttribute('aria-pressed'), 'true');
    await page.locator('[data-favorite="gequbao"]').click();
    await page.goto(base+'/');
    assert.equal(await page.locator('.nav-links a[href="#features"]').count(), 0);
    assert.equal(await page.locator('.nav-links a[href="movies.html"]').count(), 1);
    assert.equal(await page.locator('.nav-links a[href="resources.html"]').count(), 1);
    assert.equal(await page.locator('.nav-links a[href="stocks.html"]').count(), 1);
    assert.equal(await page.locator('.nav-links a[href="magnets.html"], .nav-links a[href="pans.html"]').count(), 0);
    await page.locator('#language-toggle').click();
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    assert.equal(await page.locator('.nav-links a[href="movies.html"]').innerText(), 'Movies');
    assert.equal(await page.locator('.nav-links a[href="resources.html"]').innerText(), 'Resources');
    assert.equal(await page.locator('.nav-links a[href="stocks.html"]').innerText(), 'Stocks');
    await page.goto(base+'/sources.html');
    const sourceCount = await page.locator('.source-card').count();
    assert.equal(sourceCount, 85);
    await page.locator('#filterInput').fill('GitHub');
    assert.equal(await page.locator('.source-card:visible').count(), 1);
    await page.locator('#copyVisibleButton').click();
    const copied = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()));
    assert.equal(copied.length, 1);
    assert.equal(copied[0].name, 'GitHub');
    assert.ok(copied[0].url.includes('%@'));
    assert.equal(await page.locator('#jsonPanel').getAttribute('open'), null);
    await page.locator('[data-source-category="academic"]').click();
    assert.equal(await page.locator('.source-card:visible').count(), 18);
    await page.locator('[data-category="academic"] .category-copy').click();
    assert.equal(JSON.parse(await page.evaluate(() => navigator.clipboard.readText())).length, 18);
    await page.locator('#filterInput').fill('PubMed');
    assert.equal(await page.locator('.source-card:visible').count(), 2);
    await page.locator('[data-category="academic"] .category-copy').click();
    assert.equal(JSON.parse(await page.evaluate(() => navigator.clipboard.readText())).length, 2);
    await page.locator('.source-card:visible .source-copy').first().click();
    const single = JSON.parse(await page.evaluate(() => navigator.clipboard.readText()));
    assert.equal(single.length, 1);
    assert.equal(single[0].name, 'PubMed');
    await page.locator('#filterInput').fill('google 通用');
    assert.equal(await page.locator('.source-card:visible').count(), 2);
    await page.locator('#filterInput').fill('missing-search-platform');
    assert.equal(await page.locator('.source-card:visible').count(), 0);
    assert.ok(await page.locator('#emptyState').isVisible());
    assert.ok(await page.locator('#copyVisibleButton').isDisabled());
    await page.locator('#source-reset').click();
    assert.equal(await page.locator('.source-card:visible').count(), sourceCount);
    await page.goto(base+'/extensions.html');
    const addon = page.locator('#search-platform-capture');
    assert.equal(await addon.locator('h2').innerText(), 'Soulo Search Platform');
    const download = await addon.locator('a[download]').getAttribute('href');
    const archive = await page.request.get(base+'/'+download);
    assert.ok(archive.ok());
    assert.equal((await archive.body()).subarray(0, 4).toString('hex'), '504b0304');
    for (const width of [320, 360, 390, 768, 1024, 1081, 1280]) {
      await page.setViewportSize({width, height: 900});
      let homeNavigation;
      for (const file of ['', 'movies.html', 'resources.html', 'stocks.html', 'reading.html', 'music.html', 'sources.html', 'privacy.html', 'extensions.html']) {
        await page.goto(base+'/'+file);
        const dimensions = await page.evaluate(() => ({viewport:innerWidth, content:document.documentElement.scrollWidth}));
        assert.ok(dimensions.content <= dimensions.viewport, `${file || 'index.html'} overflows at ${width}px: ${dimensions.content}`);
        const navigation = await page.locator('[data-shared-nav]').evaluate(header => {
          const box = selector => {
            const element = header.querySelector(selector);
            const rect = element.getBoundingClientRect();
            const style = getComputedStyle(element);
            return {x:rect.x, y:rect.y, width:rect.width, height:rect.height, font:style.fontSize, weight:style.fontWeight};
          };
          return {nav:box('.nav'), brand:box('.brand'), links:box('.nav-links'), tools:box('.nav-tools')};
        });
        if (!file) homeNavigation = navigation;
        else assert.deepEqual(navigation, homeNavigation, `Navigation differs on ${file} at ${width}px`);
        assert.deepEqual((await page.locator('[data-shared-nav] .nav-links a').allTextContents()).map(s => s.trim()), ['Sources','Movies','Resources','Reading','Music','Stocks','Soulo Extensions']);
        assert.equal(await page.locator('#language-toggle').innerText(), '中文');
        assert.equal(await page.locator('.nav-links a > svg:first-child').count(), 7);
        const tools = page.locator('.footer-links a[href="https://www.dkluge.com/zh/bag"]');
        assert.equal(await tools.getAttribute('target'), '_blank');
        assert.match(await tools.getAttribute('rel'), /noopener/);
        const extensions = page.locator('.nav-links a[href="extensions.html"]');
        const toggle = page.locator('.nav-menu-toggle');
        if (width <= 1080) {
          assert.equal(await page.locator('.nav-links').isVisible(), false);
          await toggle.click();
          assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
          assert.ok(await extensions.isVisible());
          await page.keyboard.press('Escape');
          assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
          assert.equal(await toggle.evaluate(e => e === document.activeElement), true);
          await toggle.click();
          await page.locator('main h1').click();
          assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
        } else {
          assert.equal(await toggle.isVisible(), false);
          assert.ok(await extensions.isVisible());
        }
      }
    }
    const nojs = await browser.newContext({javaScriptEnabled: false, viewport: {width: 1280, height: 900}});
    const plain = await nojs.newPage();
    await plain.goto(base+'/movies.html');
    assert.equal(await plain.locator('.movie-card:visible').count(), total);
    assert.equal(await plain.locator('.movie-category:visible').count(), movieData.categories.length);
    assert.equal(await plain.locator('.favorite-button:visible').count(), 0);
    await plain.goto(base+'/pans.html');
    await plain.waitForURL('**/resources.html#cloud-engine');
    assert.equal(await plain.locator('.movie-card:visible').count(), resourceTotal);
    assert.equal(await plain.locator('.movie-category:visible').count(), magnetData.categories.length + panData.categories.length);
    assert.equal(await plain.locator('.favorite-button:visible').count(), 0);
    await plain.goto(base+'/stocks.html');
    assert.equal(await plain.locator('.movie-card:visible').count(), stockData.sites.length);
    assert.equal(await plain.locator('.favorite-button:visible').count(), 0);
    await plain.goto(base+'/sources.html');
    assert.equal(await plain.locator('.source-card:visible').count(), sourceCount);
    assert.equal(await plain.locator('.source-copy:visible').count(), 0);
    for (const [kind, data] of [['reading', readingData], ['music', musicData]]) {
      await plain.setViewportSize({width: 390, height: 844});
      await plain.goto(base+'/'+kind+'.html');
      assert.equal(await plain.locator('.movie-card:visible').count(), data.sites.length);
      assert.equal(await plain.locator('.nav-links a:visible').count(), 7);
      assert.equal(await plain.locator('.nav-menu-toggle').isVisible(), false);
    }
    const unavailableClipboard = await browser.newContext();
    await unavailableClipboard.route('https://hm.baidu.com/**', route => route.abort());
    await unavailableClipboard.addInitScript(() => {
      Object.defineProperty(navigator, 'clipboard', {value: {writeText:async () => {throw new Error('Blocked');}}});
      document.execCommand = () => false;
    });
    const fallback = await unavailableClipboard.newPage();
    fallback.on('pageerror', error => errors.push(error.message));
    await fallback.goto(base+'/sources.html');
    await fallback.locator('#filterInput').fill('GitHub');
    await fallback.locator('#copyVisibleButton').click();
    assert.ok(await fallback.locator('#jsonPanel').evaluate(element => element.open));
    assert.equal(JSON.parse(await fallback.locator('#jsonPreview').innerText())[0].name, 'GitHub');
    // Corrupt or unavailable local storage must not prevent browsing.
    const restricted = await browser.newContext();
    await restricted.route('https://hm.baidu.com/**', route => route.abort());
    await restricted.addInitScript(() => {
      Storage.prototype.getItem = () => { throw new DOMException('Blocked', 'SecurityError'); };
      Storage.prototype.setItem = () => { throw new DOMException('Blocked', 'SecurityError'); };
    });
    const privatePage = await restricted.newPage();
    privatePage.on('pageerror', error => errors.push(error.message));
    await privatePage.goto(base+'/movies.html');
    await privatePage.locator('[data-favorite="pbkan"]').click();
    assert.match(await privatePage.locator('#movie-toast').innerText(), /仅在本页有效/);
    await privatePage.locator('#show-favorites').click();
    assert.equal(await privatePage.locator('.movie-card:visible').count(), 1);
    assert.deepEqual(errors, []);
    console.log(`PASS: merged resources and legacy favorites, stock navigation, ${readingData.sites.length} reading and ${musicData.sites.length} music entries; bilingual search, isolated favorites, icons, tools link, responsive menus, identical navigation at 7 widths, clipboard, no-JS, and blocked storage.`);
  } finally {
    await browser.close();
  }
}

main().catch(error => { console.error(error); process.exitCode = 1; });
